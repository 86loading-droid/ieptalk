"""IEP톡 v21 점검: IEP 생성기(교과·성취기준·단원·차시·중도중복장애 안내)와 학기말 종합(데모 모드)
실행: python3 -m http.server 8765 (저장소 폴더) 뒤 OUT=/tmp/shots python3 tools/v21-test.py"""
import asyncio, os, json
OUT = os.environ.get('OUT', '/tmp')
from playwright.async_api import async_playwright
U = 'http://127.0.0.1:8765/index.html?demo=1'
errs = []; ok = []
def chk(c, m): (ok if c else errs).append(m)

async def main():
  async with async_playwright() as p:
    b = await p.chromium.launch()
    for vw in [(1440, 900), (390, 844)]:
      ctx = await b.new_context(viewport={'width': vw[0], 'height': vw[1]}, locale='ko-KR', permissions=['clipboard-read', 'clipboard-write'])
      pg = await ctx.new_page()
      pg.on('pageerror', lambda e: errs.append(f'pageerror {e}'))
      await pg.goto(U); await pg.evaluate('localStorage.clear()'); await pg.goto(U)
      await pg.click('[data-uid="u-admin"]'); await pg.wait_for_timeout(500); await pg.keyboard.press('Escape')
      # ---- 자료 파일 ----
      idx = await pg.evaluate("fetch('data/cur/index.json').then(r=>r.json())")
      n = sum(sum(s['groups'].values()) for s in idx['subjects'] if not s.get('elements'))
      chk(n == 691, f'standards 691 ({n})')
      chk('제2026-2호' in idx['source']['notice'], 'source notice')
      # ---- IEP 생성기: 교과·성취기준 ----
      await pg.goto(U + '#/student/s1/goals'); await pg.wait_for_timeout(600); await pg.keyboard.press('Escape'); await pg.wait_for_timeout(200)
      await pg.click('[data-act="iep-gen"]'); await pg.wait_for_selector('.ig [data-ig="grade"]')
      chk(await pg.locator('.ig [data-ig="grade"][data-v="초4"].on').count() == 1, 'grade from student (초4)')
      chk(await pg.locator('.ig [data-ig="subj"][data-v="ss"]').count() == 0, '통합교과 not in 초3~4')
      await pg.click('.ig [data-ig="subj"][data-v="kor"]'); await pg.wait_for_selector('.ig [data-igin="unit"]')
      units = await pg.locator('.ig [data-igin="unit"] option').all_inner_texts()
      chk(any('생각을 말해요' in u for u in units), 'units 초4 국어')
      await pg.select_option('.ig [data-igin="unit"]', index=1); await pg.wait_for_selector('.ig [data-igin="lesson"]')
      lessons = await pg.locator('.ig [data-igin="lesson"] option').all_inner_texts()
      chk(any('차시' in x for x in lessons), 'lessons listed')
      await pg.select_option('.ig [data-igin="lesson"]', index=2); await pg.wait_for_timeout(200)
      codes = await pg.locator('.ig [data-igin="code"] option').evaluate_all('o=>o.map(x=>x.value).filter(Boolean)')
      chk(len(codes) == 11 and all(c.startswith('4국어') for c in codes), f'초3~4 국어 11 standards ({len(codes)})')
      await pg.select_option('.ig [data-igin="code"]', '4국어01-04'); await pg.wait_for_selector('.ig-std')
      t = await pg.inner_text('.ig-std')
      chk('[4국어01-04]' in t, 'std shown')
      chk(await pg.locator('.ig-sev li').count() >= 1 and '중도중복장애' in await pg.inner_text('.ig-sev'), 'severe guidance shown')
      chk('제2026-2호' in t, 'source line')
      await pg.click('.ig [data-ig="resp"][data-v="aac"]'); await pg.click('.ig [data-ig="level"][data-v="1"]'); await pg.click('.ig [data-ig="dis"][data-v="aut"]')
      doc = await pg.input_value('.ig-edit')
      chk('차시 목표(수준별' in doc and '▶ 대안' in doc, 'tiers + level→alt')
      chk('그림카드·AAC로' in doc, 'resp particle')
      chk('그림 일과표' in doc, 'disability supports')
      chk('중도중복장애' in doc, 'severe guidance in draft')
      await pg.click('.ig [data-ig="part"][data-v="partial"]'); doc = await pg.input_value('.ig-edit')
      chk('▶ 수정' in doc, 'part override')
      await pg.click('.ig [data-ig-act="copy"]'); await pg.wait_for_timeout(200)
      chk((await pg.evaluate('navigator.clipboard.readText()')).startswith('IEP 초안'), 'copy')
      n0 = await pg.locator('.card.goal').count()
      await pg.click('.ig [data-ig-act="save"]'); await pg.wait_for_timeout(300)
      # 일상생활 활동: 단원 + 내용 요소
      await pg.click('.ig [data-ig="subj"][data-v="dl"]'); await pg.wait_for_selector('.ig [data-igin="unit"]')
      await pg.select_option('.ig [data-igin="unit"]', index=1); await pg.wait_for_timeout(150)
      opts = await pg.locator('.ig [data-igin="code"] option').all_inner_texts()
      chk(any('보완대체의사소통의 탐색과 선택' in o for o in opts), 'daily-life elements')
      await pg.select_option('.ig [data-igin="code"]', '일상1-2'); doc = await pg.input_value('.ig-edit')
      chk('내용 요소' in doc, 'element draft')
      # 중1 정보통신활용: 지도서 차례 없음 → 직접 입력
      await pg.click('.ig [data-ig="grade"][data-v="중1"]'); await pg.click('.ig [data-ig="subj"][data-v="ict"]'); await pg.wait_for_selector('.ig [data-igin="unitFree"]')
      chk(await pg.locator('.ig [data-igin="unit"]').count() == 0, 'no units → free input')
      await pg.fill('.ig [data-igin="unitFree"]', '컴퓨터와 스마트 기기 사용하기'); await pg.locator('.ig [data-igin="lessonFree"]').focus(); await pg.wait_for_timeout(150)
      chk(await pg.locator('.ig-sugg button').count() >= 1, 'suggestions from unit words')
      ow = await pg.evaluate('document.documentElement.scrollWidth - window.innerWidth')
      chk(ow <= 1, f'no hscroll iepgen {ow}')
      await pg.screenshot(path=f'{OUT}/v21_iep_{vw[0]}.png')
      await pg.click('.ig [data-close]'); await pg.wait_for_timeout(300)
      chk(await pg.locator('.card.goal').count() == n0 + 1, 'goal saved')
      chk('국어·4국어01-04' in await pg.inner_text('#main'), 'goal domain code')
      # ---- 학기말 종합 ----
      await pg.goto(U + '#/student/s1/term'); await pg.wait_for_timeout(700)
      t = await pg.inner_text('.tr-prev')
      for k in ['학기말 종합', '1. 장애 특성', '2. IEP 목표와 진전도', '3. 문제행동 기초선과 중재', '4. 기능평가', '5. 위기행동 사후 기록', '6. 관찰 메모', '7. 평가조정', '8. 종합 의견', '9. 다음 학기 제언']:
        chk(k in t, 'sec ' + k)
      chk('소리 지르기' in t and '기초선' in t, 'behavior summary')
      chk('동기평가 2건' in t, 'fba counts')
      chk('자폐성장애' in await pg.input_value('#tr-traits'), 'traits prefill from note')
      op = await pg.input_value('#tr-opinion')
      chk('IEP 목표' in op and '관찰 메모' in op, 'opinion draft')
      await pg.click('[data-change="tr-sec"][data-k="notes"]'); await pg.wait_for_timeout(200)
      chk('6. 관찰 메모' not in await pg.inner_text('.tr-prev'), 'section toggle')
      await pg.fill('#tr-opinion', '시험 의견입니다.'); await pg.wait_for_timeout(400)
      chk('시험 의견입니다.' in await pg.inner_text('.tr-prev'), 'edit reflected')
      await pg.click('[data-act="tr-save"]'); await pg.wait_for_timeout(300)
      chk('저장됨' in await pg.inner_text('.tr-edit'), 'saved')
      await pg.click('[data-act="tr-copy"]'); await pg.wait_for_timeout(200)
      chk((await pg.evaluate('navigator.clipboard.readText()')).startswith('학기말 종합'), 'copy report')
      await pg.evaluate('window.print=()=>{}')
      await pg.click('[data-act="tr-print"]'); await pg.wait_for_timeout(200)
      chk('9. 다음 학기 제언' in await pg.inner_text('#print-root', timeout=1000) if await pg.locator('#print-root').count() else False, 'print root')
      await pg.evaluate("document.body.classList.remove('printing')")
      await pg.click('[data-act="tr-term"][data-v="1"]'); await pg.wait_for_timeout(300)
      chk('-03-01' in await pg.inner_text('.tr-bar'), 'term 1 range')
      await pg.goto(U + '#/student/s1/memo'); await pg.wait_for_timeout(400)
      chk('시험 의견입니다' not in await pg.inner_text('#main'), 'term memo hidden from shared memo')
      await pg.goto(U + '#/student/s1/term'); await pg.wait_for_timeout(400)
      ow = await pg.evaluate('document.documentElement.scrollWidth - window.innerWidth')
      chk(ow <= 1, f'no hscroll term {ow}')
      await pg.screenshot(path=f'{OUT}/v21_term_{vw[0]}.png', full_page=True)
      # 보조인력에게는 학기말 종합 탭이 없어야 함(교사 자료)
      await ctx.close()
    await b.close()
asyncio.run(main())
print('OK', len(ok)) if not errs else print('FAIL', errs, 'ok', len(ok))
