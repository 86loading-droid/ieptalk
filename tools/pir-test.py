import asyncio, sys, os
OUT = os.environ.get('OUT', '/tmp')
from playwright.async_api import async_playwright
BASE='http://127.0.0.1:8765/index.html?demo=1'
errs=[]; ok=[]
def chk(c,msg): (ok if c else errs).append(msg)
async def main():
  async with async_playwright() as p:
    b=await p.chromium.launch()
    for vw in [(1440,900),(390,844)]:
      ctx=await b.new_context(viewport={'width':vw[0],'height':vw[1]},locale='ko-KR',permissions=['clipboard-read','clipboard-write'])
      pg=await ctx.new_page()
      pg.on('pageerror',lambda e: errs.append(f'pageerror {e}'))
      pg.on('console',lambda m: errs.append('console '+m.text) if m.type=='error' and 'CORS' not in m.text and 'Failed to load resource' not in m.text and 'fetch' not in m.text.lower() else None)
      await pg.goto(BASE); await pg.evaluate('localStorage.clear()'); await pg.goto(BASE)
      await pg.click('[data-uid="u-admin"]'); await pg.wait_for_selector('#main'); await pg.wait_for_timeout(500); await pg.keyboard.press('Escape')
      await pg.goto('http://127.0.0.1:8765/index.html?demo=1#/student/s1/crisis'); await pg.wait_for_timeout(800)
      chk(await pg.locator('[data-act="pir-open"]').count()>0, 'card report button')
      chk('보고서 작성 중' in await pg.inner_text('#main'), 'status tag 작성 중')
      await pg.locator('[data-act="pir-open"]').first.click(); await pg.wait_for_selector('.pr-doc')
      doc=await pg.inner_text('.pr-doc')
      chk('신체적 개입(물리적 제지) 사후 보고서' in doc and '6. 신체적 개입 방법' in doc, 'report built')
      chk('접촉 시간 약 3분' in doc, 'duration computed')
      chk('없었음을 작성자가 확인' in doc, 'safe list')
      # 상세 예시 드롭다운
      miss=await pg.evaluate('''async()=>{const m=await import('./js/views/pirexamples.js');const ids=[...document.querySelectorAll('.pr-chip')].map(b=>b.dataset.id);return ids.filter(i=>!(m.EX[i]&&m.EX[i].length>=5&&m.EX[i].length<=10));}''')
      chk(len(miss)==0, f'all chips 5-10 examples {miss}')
      sel=pg.locator('.pr-group[data-cat="beh"] .pr-det select')
      chk(await sel.locator('option').count()>=6, 'beh dropdown options')
      await sel.select_option(index=1)
      chk('(오른손 주먹으로 교사의 어깨를 2회 침)' in await pg.inner_text('.pr-doc'), 'example into sentence')
      chk(await pg.locator('.pr-group[data-cat="beh"] .pr-det input').input_value()=='오른손 주먹으로 교사의 어깨를 2회 침', 'example fills input')
      await pg.locator('.pr-group[data-cat="beh"] .pr-det input').fill('오른손 주먹으로 교사의 왼쪽 어깨를 3회 침')
      chk('(오른손 주먹으로 교사의 왼쪽 어깨를 3회 침)' in await pg.inner_text('.pr-doc'), 'edited detail into sentence')
      await pg.locator('.pr-group[data-cat="body"] .pr-det select').select_option(label='오른쪽 아래팔')
      chk('접촉 부위는 오른쪽 아래팔입니다' in await pg.inner_text('.pr-doc'), 'body detail replaces word')
      await pg.click('.pr-group[data-cat="beh"] [data-pr="edit"]')
      await pg.locator('.pr-group[data-cat="beh"] .pr-edit li').first.locator('[data-pe=x]').fill('예시 하나\n예시 둘')
      await pg.click('.pr-group[data-cat="beh"] [data-pr="edit"]')
      chk(await pg.locator('.pr-group[data-cat="beh"] .pr-det select option').count()==4, 'edited examples (2 + placeholder + own)')
      chk('(오른손 주먹으로 교사의 왼쪽 어깨를 3회 침)' in await pg.inner_text('.pr-doc'), 'detail kept after chip edit')
      # toggle chip
      await pg.click('.pr-group[data-cat="pre"] [data-id="pre5"]')
      doc2=await pg.inner_text('.pr-doc'); chk('4) 주변의 다칠 수 있는 물건을 치웠습니다.' in doc2, 'chip toggle adds ordered sentence')
      # subjective word warning
      await pg.fill('textarea[name="behDetail"]', '학생이 흥분하여 책상을 침')
      chk('해석이 섞인 낱말' in await pg.inner_text('.pr-warn'), 'subjective warning')
      # edit chips: rename and add
      await pg.click('.pr-group[data-cat="pre"] [data-pr="edit"]')
      await pg.locator('.pr-group[data-cat="pre"] .pr-edit li').first.locator('[data-pe=l]').fill('말로 안내')
      await pg.locator('.pr-group[data-cat="pre"] .pr-edit li').first.locator('[data-pe=t]').fill('낮은 목소리로 「멈춰요」라고 두 번 말하였습니다.')
      await pg.click('.pr-group[data-cat="pre"] [data-pr="add"]')
      li=pg.locator('.pr-group[data-cat="pre"] .pr-edit li').last
      await li.locator('[data-pe=l]').fill('타이머 보여주기'); await li.locator('[data-pe=t]').fill('남은 시간을 타이머로 보여 주었습니다.')
      await pg.click('.pr-group[data-cat="pre"] [data-pr="edit"]')
      chk(await pg.locator('.pr-group[data-cat="pre"] .pr-chip', has_text='타이머 보여주기').count()==1, 'new chip appears')
      chk('낮은 목소리로' in await pg.inner_text('.pr-doc'), 'renamed chip sentence updates selection')
      await pg.locator('.pr-group[data-cat="pre"] .pr-chip', has_text='타이머 보여주기').click()
      chk('남은 시간을 타이머로' in await pg.inner_text('.pr-doc'), 'custom chip into report')
      # copy
      await pg.click('[data-pr="copy"]'); await pg.wait_for_timeout(200)
      clip=await pg.evaluate('navigator.clipboard.readText()')
      chk(clip.startswith('신체적 개입(물리적 제지) 사후 보고서') and '9. 보고와 통지' in clip, 'clipboard copy')
      # finalize
      await pg.click('[data-pr="final"]'); await pg.wait_for_timeout(300)
      st=await pg.inner_text('.pr-status'); chk('확정됨' in st, 'finalized:'+st)
      chk('문서 확인값' in await pg.inner_text('.pr-doc'), 'hash in doc')
      await pg.fill('textarea[name="extra"]','추가 사실'); st=await pg.inner_text('.pr-status'); chk('확정 뒤 고침' in st, 'changed after final')
      await pg.click('[data-pr="final"]'); await pg.wait_for_timeout(300)
      chk(await pg.locator('.pr-hist li').count()==2, 'history 2')
      await pg.click('.pr-top [data-close]')
      await pg.wait_for_timeout(300)
      chk('보고서 확정 · 정정 1' in await pg.inner_text('#main'), 'card shows 정정 1')
      # persisted chips after reopen
      await pg.locator('[data-act="pir-new"]').first.click(); await pg.wait_for_selector('.pr-doc')
      chk(await pg.locator('.pr-group[data-cat="pre"] .pr-chip', has_text='타이머 보여주기').count()==1, 'chips persisted')
      chk('[적지 않음: 장소]' in await pg.inner_text('.pr-doc'), 'missing markers')
      await pg.fill('input[name="place"]','특수학급'); await pg.click('[data-pr="save"]'); await pg.wait_for_timeout(300)
      chk('저장됨' in await pg.inner_text('.pr-status'), 'new saved')
      ow=await pg.evaluate('document.querySelector(".modal").scrollWidth - document.querySelector(".modal").clientWidth')
      chk(ow<=1, f'no modal hscroll {ow}')
      await pg.screenshot(path=f'{OUT}/pir_{vw[0]}.png', full_page=False)
      await pg.click('.pr-top [data-close]'); await pg.wait_for_timeout(300)
      chk(await pg.locator('.card.incident').count()==2, 'two incidents now')
      await ctx.close()
    await b.close()
asyncio.run(main())
print('OK',len(ok)); print('\n'.join('FAIL '+e for e in errs)); sys.exit(1 if errs else 0)
