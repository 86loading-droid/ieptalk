"""IEP톡 v23 점검: IEP 초안 바로 고치기, 목표 카드의 IEP 문서 고치기, 학생 「지금 현황」(모니터) 첫 화면
실행: python3 -m http.server 8765 (저장소 폴더) 뒤 OUT=/tmp/shots python3 tools/v23-test.py"""
import asyncio, os
OUT = os.environ.get('OUT', '/tmp')
from playwright.async_api import async_playwright
B = 'http://127.0.0.1:8765/index.html'
errs = []; ok = []
def chk(c, m): (ok if c else errs).append(m)

async def main():
  async with async_playwright() as p:
    b = await p.chromium.launch()
    for vw in [(1440, 900), (390, 844)]:
      ctx = await b.new_context(viewport={'width': vw[0], 'height': vw[1]}, locale='ko-KR')
      pg = await ctx.new_page()
      pg.on('pageerror', lambda e: errs.append(f'pageerror {e}'))
      await pg.goto(B + '?demo=1&as=admin'); await pg.wait_for_timeout(1200)
      # ---- 학생 화면 첫 탭 = 지금 현황 ----
      await pg.goto(B + '?demo=1&as=admin#/students'); await pg.wait_for_timeout(600)
      await pg.click('.stu-card >> nth=0'); await pg.wait_for_timeout(800)
      chk('/now' in pg.url, 'student card opens now ' + pg.url)
      await pg.goto(B + '?demo=1&as=admin#/student/s1'); await pg.wait_for_timeout(800)
      chk(await pg.locator('.tabs a.on').inner_text() == '지금 현황', 'default tab now')
      chk((await pg.locator('.tabs a').first.inner_text()) == '지금 현황', 'first tab')
      chk(await pg.locator('.mo-tile').count() == 6, 'six tiles')
      chk(await pg.locator('.mo-steps .mo-st').count() == 7, 'step diagram 7')
      chk(await pg.locator('.mo-goal .mo-bar').count() >= 1, 'goal bars')
      chk(await pg.locator('.mo-bar-exp').count() >= 1, 'expected line')
      chk(await pg.locator('.mo-chart').count() >= 1, 'behavior chart')
      chk(await pg.locator('.mo-radar').count() == 1, 'function radar')
      chk(await pg.locator('.mo-tl circle').count() >= 3, 'timeline dots')
      chk(await pg.locator('.mo-todo li').count() >= 1, 'todo')
      t = await pg.inner_text('#main')
      chk('주된 기능' in t and '최근 30일' in t and '다음 할 일' in t, 'monitor text')
      ow = await pg.evaluate('document.documentElement.scrollWidth - window.innerWidth')
      chk(ow <= 1, f'no hscroll monitor {ow}')
      await pg.screenshot(path=f'{OUT}/v23_now_{vw[0]}.png', full_page=True)
      await pg.click('.mo-tile >> nth=0'); await pg.wait_for_timeout(500)
      chk('/goals' in pg.url, 'tile → goals')
      await pg.evaluate('window.print=()=>{}')
      await pg.goto(B + '?demo=1&as=admin#/student/s1/now'); await pg.wait_for_timeout(600)
      await pg.click('[data-act="mo-print"]'); await pg.wait_for_timeout(200)
      chk(await pg.locator('#print-root .mo-radar').count() == 1, 'monitor print')
      await pg.evaluate("document.body.classList.remove('printing')")
      # ---- IEP 생성기: 초안 바로 고치기 ----
      await pg.goto(B + '?demo=1&as=admin#/student/s1/goals'); await pg.wait_for_timeout(600)
      n0 = await pg.locator('.goal').count()
      await pg.click('[data-act="iep-gen"]'); await pg.wait_for_timeout(600)
      await pg.click('.ig [data-ig="grade"][data-v="초3"]'); await pg.wait_for_timeout(300)
      await pg.click('.ig [data-ig="subj"][data-v="kor"]'); await pg.wait_for_timeout(900)
      await pg.select_option('.ig [data-igin="code"]', index=1); await pg.wait_for_timeout(400)
      chk(await pg.locator('textarea.ig-edit').count() == 1, 'draft is textarea')
      v0 = await pg.input_value('.ig-edit')
      chk('장기 목표' in v0, 'draft text')
      chk('자동 초안' in await pg.inner_text('[data-ig-state]'), 'state auto')
      await pg.fill('.ig-edit', v0 + '\n\n교사 메모: 받침 없는 낱말부터 시작')
      chk('고친 글' in await pg.inner_text('[data-ig-state]'), 'state edited')
      chk(await pg.locator('[data-ig-act="reset"]').is_visible(), 'reset visible')
      # 다른 선택을 바꿔도 고친 글 유지 + 새 초안 알림
      await pg.click('.ig [data-ig="part"][data-v="alt"]'); await pg.wait_for_timeout(300)
      v1 = await pg.input_value('.ig-edit')
      chk('받침 없는 낱말' in v1, 'edit kept after repaint')
      chk(await pg.locator('.ig-stale').count() == 1, 'stale notice')
      # 목표 카드 조건·행동·기준 고치기
      await pg.click('.ig-gf summary')
      await pg.fill('[data-iggf="criterion"]', '10회 중 7회 이상, 3회기 연속')
      chk('모두 들어 있습니다' in await pg.inner_text('[data-ig-miss]'), 'gf ok')
      await pg.click('[data-ig-act="save"]'); await pg.wait_for_timeout(600)
      await pg.click('.ig [data-close]'); await pg.wait_for_timeout(400)
      chk(await pg.locator('.goal').count() == n0 + 1, 'goal saved')
      gt = await pg.inner_text('#main')
      chk('10회 중 7회 이상, 3회기 연속' in gt, 'edited criterion saved')
      last = pg.locator('.goal-doc', has_text='교사가 고친 글')
      chk(await last.count() == 1, 'goal doc marked edited')
      await last.locator('summary').click()
      chk('받침 없는 낱말' in await last.inner_text(), 'edited text saved')
      # 저장 뒤에도 문서 고치기
      await last.locator('[data-act="goal-edit"]').click(); await pg.wait_for_timeout(400)
      ta = pg.locator('.modal textarea[name="note"]')
      chk(await ta.count() == 1 and 'IEP 초안' in await ta.input_value(), 'note editable in goal form')
      await ta.fill((await ta.input_value()) + '\n추가: 보호자 협의 반영')
      await pg.click('.modal button[type="submit"]'); await pg.wait_for_timeout(500)
      await pg.locator('.goal-doc', has_text='교사가 고친 글').locator('summary').click()
      chk('보호자 협의 반영' in await pg.inner_text('#main'), 'note edit saved')
      # 처음 초안으로 되돌리기(두 번 누르기)
      await pg.click('[data-act="iep-gen"]'); await pg.wait_for_timeout(600)
      await pg.click('.ig [data-ig="grade"][data-v="초3"]'); await pg.wait_for_timeout(300)
      await pg.click('.ig [data-ig="subj"][data-v="kor"]'); await pg.wait_for_timeout(600)
      await pg.select_option('.ig [data-igin="code"]', index=1); await pg.wait_for_timeout(300)
      base = await pg.input_value('.ig-edit')
      await pg.fill('.ig-edit', 'X')
      await pg.click('[data-ig-act="reset"]'); chk(await pg.input_value('.ig-edit') == 'X', 'reset needs 2nd press')
      await pg.click('[data-ig-act="reset"]'); await pg.wait_for_timeout(200)
      chk(await pg.input_value('.ig-edit') == base, 'reset to draft')
      # 생활 기능 모드도 글상자
      await pg.click('.ig [data-mode="life"]'); await pg.wait_for_timeout(200)
      await pg.click('.ig [data-ig="course"] >> nth=0'); await pg.click('.ig [data-ig="subj2"] >> nth=0'); await pg.click('.ig [data-ig="area"] >> nth=0'); await pg.wait_for_timeout(200)
      chk(await pg.locator('textarea.ig-edit').count() == 1, 'life mode textarea')
      ow = await pg.evaluate('document.documentElement.scrollWidth - window.innerWidth')
      chk(ow <= 1, f'no hscroll gen {ow}')
      await pg.screenshot(path=f'{OUT}/v23_gen_{vw[0]}.png')
      await ctx.close()
    await b.close()
asyncio.run(main())
print('OK', len(ok)) if not errs else print('FAIL', errs, 'ok', len(ok))
